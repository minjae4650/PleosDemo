using System;
using UnityEngine;

namespace BusanEnvironment
{
    /// <summary>One drivable polyline for ambient traffic; cars travel in point order, `lane` metres to the right.</summary>
    [Serializable]
    public sealed class TrafficPath
    {
        public Vector3[] points;
        public float lane;
        public float width;
    }

    /// <summary>A fixed-time signal program (SUMO tlLogic): phase durations and one state character per controlled link.</summary>
    [Serializable]
    public sealed class SignalProgram
    {
        public float offset;
        public float[] durations;
        public string[] states;
    }

    /// <summary>One signal head (one approach of a junction) and the link indices it shows: straight, left, right.</summary>
    [Serializable]
    public sealed class SignalHead
    {
        public int program;
        public int[] straight;
        public int[] left;
        public int[] right;
    }

    /// <summary>A place on a traffic path where cars stop when their head shows red. path -1 = the course.</summary>
    [Serializable]
    public struct SignalStop
    {
        public int path;
        public int dir;
        public float s;
        public int head;
        public int group;   // 0 straight, 1 left, 2 right
    }

    /// <summary>
    /// Baked traffic geometry kept outside the scene file: the course path with per-point road width,
    /// one-way flag and speed limit, plus arterial corridors (secondary and above within 300 m of the course),
    /// and the traffic signals (programs, heads, stop positions on the paths).
    /// Generated by the Busan slice builder.
    /// </summary>
    public sealed class TrafficData : ScriptableObject
    {
        public Vector3[] course;
        public float[] courseWidth;
        public bool[] courseOneWay;
        public float[] courseSpeed;
        public TrafficPath[] corridors;
        public SignalProgram[] programs;
        public SignalHead[] heads;
        public SignalStop[] stops;
    }
}
