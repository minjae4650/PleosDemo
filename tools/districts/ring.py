    scene = {'note': NOTE, 'heading': heading, 'sunYaw': 0.0, 'sunPitch': 38.0, 'probe': probes[0]['pos'], 'probes': probes,
             'cars': parked, 'views': views, 'colliders': colliders}
    return kit, scene
