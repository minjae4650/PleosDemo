    for s in np.arange(75.0, float(tn.s[-1]) - 40.0, 150.0):
        i = at_s(s)
        tx, tz = float(tn.t[i][0]), float(tn.t[i][1])
        for o in (tn.right * 0.5 - 0.85, tn.right * 0.5 + 0.85):
            c = tn.xz[i] + tn.r[i] * o
            M['tunnel_fan'].obox(float(c[0]), float(c[1]), tx, tz, 2.1, 0.55, ROAD_Y + TUBE_H - 1.45, ROAD_Y + TUBE_H - 0.35, bottom=True)
            for e in (-2.12, 2.12):                                            # the dark mouths of the fan
                q = c + tn.t[i] * e
                M['tunnel_conc'].obox(float(q[0]), float(q[1]), tx, tz, 0.02, 0.42, ROAD_Y + TUBE_H - 1.32, ROAD_Y + TUBE_H - 0.48, (0.25, 0.25, 0.25), top=False)
            M['tunnel_fan'].obox(float(c[0]), float(c[1]), tx, tz, 0.08, 0.08, ROAD_Y + TUBE_H - 0.35, ROAD_Y + TUBE_H, (0.8, 0.8, 0.8), top=False)
    for i, away in ((0, -1.0), (tn.n - 1, 1.0)):
        ux, uz = float(tn.t[i][0] * away), float(tn.t[i][1] * away)

        def at(off, y):
            q = tn.xz[i] + tn.r[i] * off + tn.t[i] * away * 0.3
            return (float(q[0]), ROAD_Y + y, float(q[1]))
        # beside the tube a second mouth, for the other direction: the oncoming lanes of the road outside run into it, and the
        # moving cars of that direction come out of one and go into the other (tools/network.py, traffic). It is 28 m deep.
        s0, s1, sh = wl - 7.6, wl - 0.9, 5.0

        def inside(off, y, deep):
            q = tn.xz[i] + tn.r[i] * off - tn.t[i] * away * deep
            return (float(q[0]), ROAD_Y + y, float(q[1]))
        inward = (float(-tn.t[i][0] * away), 0.0, float(-tn.t[i][1] * away))
        M['tunnel_floor'].quad(inside(s0, 0.0, -0.3), inside(s1, 0.0, -0.3), inside(s1, 0.0, 28.0), inside(s0, 0.0, 28.0), (0.0, 1.0, 0.0),
                               ((0, 0), (1.7, 0), (1.7, 7), (0, 7)))
        M['tunnel_conc'].quad(inside(s0, sh, -0.3), inside(s1, sh, -0.3), inside(s1, sh, 28.0), inside(s0, sh, 28.0), (0.0, -1.0, 0.0))
        for off, facing in ((s0, 1.0), (s1, -1.0)):
            out = (float(tn.r[i][0] * facing), 0.0, float(tn.r[i][1] * facing))
            M['tunnel_tile'].quad(inside(off, 0.0, -0.3), inside(off, 0.0, 28.0), inside(off, 2.7, 28.0), inside(off, 2.7, -0.3), out, ((0, 0), (9.3, 0), (9.3, 0.9), (0, 0.9)))
            M['tunnel_conc'].quad(inside(off, 2.7, -0.3), inside(off, 2.7, 28.0), inside(off, sh, 28.0), inside(off, sh, -0.3), out)
        M['tunnel_conc'].quad(inside(s0, 0.0, 28.0), inside(s1, 0.0, 28.0), inside(s1, sh, 28.0), inside(s0, sh, 28.0), (-inward[0], 0.0, -inward[2]), col=(0.25, 0.25, 0.25))
        for deep in (5.0, 13.0, 21.0):
            c = tn.xz[i] + tn.r[i] * (s0 + s1) / 2 - tn.t[i] * away * deep
            M['tunnel_lamp'].obox(float(c[0]), float(c[1]), float(tn.t[i][0]), float(tn.t[i][1]), 1.3, 0.22, ROAD_Y + sh - 0.14, ROAD_Y + sh - 0.02, top=False, bottom=True)
        for o0, o1, y0, y1 in ((wl - 16.0, s0, -0.2, 17.0), (s0, s1, sh, 17.0), (s1, wl, -0.2, 17.0), (wr, wr + 16.0, -0.2, 17.0), (wl, wr, TUBE_H, 17.0)):
            M['stone'].quad2(at(o0, y0), at(o1, y0), at(o1, y1), at(o0, y1), (ux, 0.0, uz), col=(0.66, 0.66, 0.64))
        rx, rz = float(tn.r[i][0]), float(tn.r[i][1])

        def slab(o0, o1, y0, y1, depth, col):
            c = tn.xz[i] + tn.r[i] * (o0 + o1) / 2 + tn.t[i] * away * (0.3 + depth / 2)
            M['stone'].obox(float(c[0]), float(c[1]), rx, rz, abs(o1 - o0) / 2, depth / 2, ROAD_Y + y0, ROAD_Y + y1, col, 2.0, bottom=True)
        slab(s1, wl, -0.1, TUBE_H + 1.1, 0.5, LIGHT)                             # the frame (this post stands between the two mouths)
        slab(wr, wr + 1.1, -0.1, TUBE_H + 1.1, 0.5, LIGHT)
        slab(wl - 1.1, wr + 1.1, TUBE_H, TUBE_H + 1.1, 0.5, LIGHT)
        slab(wl - 16.4, wr + 16.4, 17.0, 17.5, 0.7, LIGHT)                       # the coping
        slab(wl - 16.4, wr + 16.4, 11.0, 11.25, 0.12, DARK)                      # a shadow joint across the wall
        for o in list(np.arange(wl - 16.0, wl - 1.5, 3.6)) + list(np.arange(wr + 1.6, wr + 16.1, 3.6)):
            slab(o - 0.04, o + 0.04, sh + 0.9 if s0 - 0.9 < o < s1 + 0.9 else 0.0, 17.0, 0.04, DARK)
        slab(s0 - 0.7, s0, -0.1, sh + 0.7, 0.5, LIGHT)                           # the second mouth's frame
        slab(s0 - 0.7, s1, sh, sh + 0.7, 0.5, LIGHT)
        if away < 0:                                                             # the name, over the mouth the driver enters by
            c = tn.xz[i] + tn.r[i] * (wl + wr) / 2 + tn.t[i] * away * 0.62
            guide.board(kit, 'tunnel', (float(c[0]), ROAD_Y + TUBE_H + 2.6, float(c[1])), (rx, rz), 5.4, 1.8)

    # ---- the surfaces the car drives on: one flat sheet for the streets, one strip for each ramp and for the bridge
    colliders = {}
    # Every lane that is paved can be driven, in both directions: a player who turns round, or takes the other carriageway,
    # stood still at the first metre without a surface under it (the car stops where the surface ends).
    drive = unary_union([p for p in fwd] + back + boxes + lanes + [g_road]).buffer(0.5).buffer(-0.5).difference(median.buffer(0.15)).difference(under_holes)
    sheet = Mesh(False)
    sheet.polygon(drive.buffer(-INSET), flat(ROAD_Y))
    colliders['Streets'] = sheet
    # the ramps widen to the span's four lanes and narrow back as districts/bridge.py draws them (the surface used to stay
    # two lanes wide to the joint: the span's two right lanes ended in nothing where the down ramp begins)
    a1r, a2r, a3r = roads['A1'], roads['A2'], roads['A3']
    wide_, narrow_ = a2r.right, a1r.right
    deck_edge = {'A1': [narrow_ + (wide_ - narrow_) * ease((v - (a1r.s[-1] - 110.0)) / 100.0) for v in a1r.s],
                 'A2': [wide_] * a2r.n,
                 'A3': [wide_ - (wide_ - narrow_) * ease((v - 10.0) / 100.0) for v in a3r.s]}
    for r in drawn:
        if r.kind in ('ramp', 'bridge'):
            strip = Mesh(False)
            o0 = r.median / 2 - 0.5 + INSET
            hi = deck_edge.get(r.id, [r.right] * r.n)
            for i in range(r.n - 1):
                strip.quad(r.P(i, o0), r.P(i + 1, o0), r.P(i + 1, hi[i + 1] + 0.5 - INSET), r.P(i, hi[i] + 0.5 - INSET), (0.0, 1.0, 0.0))
            colliders[r.id] = strip

    # ---- views: the driver's eye every 150 m of each route
    views = []
    for k, route in enumerate(net['routes']):
        line, y, n = route['_line'], route['_y'], len(route['_line'])
        s, step = 0.0, 0.0
        for i in range(n):
            d = float(np.linalg.norm(line[(i + 1) % n] - line[i]))
            if step <= 0.0:
                j = (i + 10) % n
                views.append({'name': 'R%d_%04d_driver' % (k, round(s)), 'px': float(line[i][0]), 'py': float(y[i] + 1.2), 'pz': float(line[i][1]),
                              'tx': float(line[j][0]), 'ty': float(y[j] + 0.95), 'tz': float(line[j][1]), 'fov': 62})
                step = 150.0
