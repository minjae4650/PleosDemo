"""The whole loop in grey: every road of tools/network.py as plain asphalt with kerbs, sidewalks, lane lines, parapets on the
ramps and the bridge, a box tunnel, the sea, flat land with a sea wall and the hill inside the loop; and the surfaces the car
drives on.

This is the first stage of the compressed Busan map (plan.md, T5): both routes can be driven end to end before any district
is dressed. A district that has been built takes over its part: the Gwangalli district has its own road and ground (this file
stays out of its region), and the segments named in DRESSED are drawn by their own district (here only their driving surface
and what lies at street level remain).

The car is held on the road only by where the driving surface ends, and it sees the surface under the middle of each axle, so
the driving surfaces stop 0.95 m short of kerbs, medians and parapets (half a car's width)."""
