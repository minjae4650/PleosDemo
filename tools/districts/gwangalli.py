"""500 m of 광안해변로 (Gwangalli beach road), the district first built by tools/build-gwangalli-blockout.py (kept as the reference;
this file reproduces its JSON byte for byte, so the calls below keep its order).

Aim (the user's words, 2026-11-11): keep only the overall structure of the real place, give up real proportions and sizes, and
make what the driver sees up close feel real. So the near field is built in detail (asphalt, gutter, kerb stones, paving, shop
fronts with glass, frames, doors and signs, promenade furniture, queued cars) and the far field is a silhouette (skyline boxes,
the bridge, hills). No people (decided), and no trees until they can be made realistic. One thing is made larger than life on
purpose: the beach's lettering sculpture ("안녕, 광안리"), so the place is recognised at a glance from the driver's seat.

Structure from the OpenStreetMap extracts in docs/concepts (ODbL): road line, beach outline, building footprints and storeys,
side streets. What stands there from two roadview observations (2026-03); nothing is copied from them, signs carry generic words.
Estimates: road height 4 m, lane width, bridge deck and tower heights, storeys of untagged buildings, every furniture spacing."""
import json
import math

import numpy as np
from shapely.geometry import LineString, Point, Polygon, box
from shapely.ops import unary_union

from busan_kit import bridge, frontage, landmark, street, terrain, views
from busan_kit.geo import DATA, osm, proj, road_centre, way_line
from busan_kit.kit import Kit
from busan_kit.materials import MAT
from busan_kit.textures import make_textures

# the old generator's note, kept word for word so the JSON stays identical to the reference
NOTE = 'Generated by tools/build-gwangalli-blockout.py. Map data from OpenStreetMap contributors (ODbL).'
SEED = 1110

ROAD_WAY = 165503746
STRETCH = ((5081.0, 3338.0), (5354.0, 3736.0))
MARGIN = 90.0
ROAD_Y = 4.0
KERB = 0.16
BASE = ROAD_Y + KERB          # paving level
HALF = 3.5
SAND_TOP = BASE - 0.45
DECK_Y, DECK_DEPTH, DECK_W, TOWER_Y = 40.0, 9.0, 24.0, 105.0

BANNERS = [(0.10, 0.34, 0.60), (0.86, 0.46, 0.10), (0.10, 0.48, 0.44)]
# cars standing in the road (the project's own Hyundai models), as on the real street: metres past the start, offset, facing
# against the road, model
CARS = ((78, -1.75, True, 'Hyundai_Tucson_White'), (86.5, -1.75, True, 'Hyundai_Azera_Silver'), (95, -1.7, True, 'Hyundai_i30_Blue'),
        (205, -1.75, True, 'Hyundai_Tucson_Graphite'), (250, 1.75, False, 'Hyundai_Azera_Navy'), (330, 1.75, False, 'Hyundai_i30_Black'),
        (345, -1.75, True, 'Hyundai_Tucson_Black'), (440, 1.7, False, 'Hyundai_Porter_II_Blue'),
        (62, 1.75, False, 'Hyundai_Azera_Silver'), (128.5, -1.75, True, 'Hyundai_i30_Burgundy'), (136.5, -1.7, True, 'Hyundai_Tucson_Black'),
        (192, 1.8, False, 'Generic_DeliveryTruck'), (300, -1.75, True, 'Hyundai_Azera_Navy'), (388, 1.75, False, 'Hyundai_Tucson_White'),
        (412, -1.75, True, 'Hyundai_i30_Burgundy'), (470, -1.7, True, 'Hyundai_Tucson_Graphite'))


def build(tex_dir, legacy=True):
    """Makes the textures in `tex_dir` and builds the district. Returns the kit (its meshes) and the rest of the scene for output.

    legacy=True is the stand-alone scene of the old generator, byte for byte. legacy=False is the district inside the landmark
    map: only what stands on its own ground (the region tools/network.py gives it), no sea, far shore, hills or distant bridge of
    its own (the ring and the bridge district have those), nothing standing in the lane the player now drives (the shop side,
    toward the south-west: the map enters from Haeundae), and views for that direction."""
    make_textures(tex_dir)
    streets = osm('busan-slice-streets-osm.json')
    way = next(w for w in streets if w['id'] == ROAD_WAY)
    centre, start = road_centre(way, STRETCH[0], STRETCH[1], MARGIN)
    kit = Kit(MAT, SEED, ROAD_Y, KERB, HALF, centre)
    rng, pose, LEN = kit.rng, kit.pose, kit.LEN
    heading = math.atan2(centre.coords[-1][1] - centre.coords[0][1], centre.coords[-1][0] - centre.coords[0][0])   # angle of the road in the x-z plane
    s_mark = start + 250.0                                 # where the name letters stand (the landmark, below)

    zone = centre.buffer(420.0, cap_style='flat')
    landcover = osm('busan-slice-landcover-osm.json')
    beach = unary_union([Polygon([proj(p['lat'], p['lon']) for p in e['geometry']]).buffer(0) for e in landcover
                         if e.get('tags', {}).get('natural') == 'beach' and len(e.get('geometry', [])) >= 3]).intersection(zone)
    land_side = centre.buffer(170.0, single_sided=True)
    sea_side = centre.buffer(-420.0, single_sided=True)
    road_main = centre.buffer(HALF, cap_style='flat')

    # side streets on the town side (광남로 xx번길): asphalt between the buildings, open onto the beach road
    alleys = []
    for w in streets:
        if w['id'] == ROAD_WAY or len(w.get('geometry', [])) < 2 or w.get('tags', {}).get('highway') not in ('residential', 'service', 'unclassified', 'living_street', 'tertiary'):
            continue
        ln = way_line(w)
        if ln.intersects(land_side):
            alleys.append(ln.buffer(3.0, cap_style='flat'))
    alley_area = unary_union(alleys).intersection(land_side).difference(road_main) if alleys else Polygon()

    sidewalk = centre.buffer(12.0, single_sided=True).difference(road_main).difference(alley_area)
    yard = land_side.difference(road_main).difference(alley_area).difference(sidewalk)
    promenade = centre.buffer(-40.0, single_sided=True).difference(road_main).difference(beach)
    sand_all = beach.intersection(sea_side).difference(promenade).difference(road_main)
    step1 = sand_all.intersection(promenade.buffer(0.45))
    step2 = sand_all.intersection(promenade.buffer(0.90)).difference(step1)
    sand = sand_all.difference(step1).difference(step2)
    water = sea_side.difference(beach).difference(promenade).difference(road_main)

    # ---- carriageway
    inner = street.carriageway(kit, road_main, alley_area)
    street.kerbs(kit, gaps=alley_area.buffer(0.3))
    street.lane_lines(kit)
    for s in np.arange(start % 70.0 + 20.0, LEN - 10.0, 70.0):
        for off, turn in ((HALF / 2 - 0.1, 0.0), (-(HALF / 2 - 0.1), math.pi)):
            street.arrow(kit, s + (18.0 if turn else 0.0), off, turn)
    for k in range(int(LEN / 43.0)):                       # manhole covers
        street.manhole(kit, 20.0 + k * 43.0 + rng.uniform(-6, 6), rng.choice([-1.9, 1.7, 0.9, -0.8]))
    street.side_street_mouths(kit, alley_area)

    # ---- town side: sidewalk, tactile strip, yards
    street.town_side(kit, sidewalk, yard)

    # ---- sea side: promenade with a granite border, steps down to the sand
    street.promenade(kit, promenade, step1, step2)
    water_edge = water.difference(centre.buffer(40.0)).buffer(0.5)
    terrain.beach_sand(kit, sand, water_edge, SAND_TOP)
    if legacy:
        terrain.sea(kit, box(2500, 0, 9000, 6500))

    def promenade_width(s):
        return street.promenade_width(kit, sand_all, s)

    # furniture: stone bollards along the kerb, lamps, planters with a stone rim (no trees yet), benches facing the sea
    for s in np.arange(1.5, LEN, 3.0):
        x, z, _, _ = pose(s, HALF + 0.6)
        street.bollard(kit, x, z)
    for k, s in enumerate(np.arange(14.0, LEN, 36.0)):
        street.lamp(kit, s, HALF + 1.2, -1.0, BANNERS[k % 3])
        if not alley_area.buffer(1.5).contains(Point(*pose(s + 18.0, -(HALF + 0.8))[:2])):
            street.lamp(kit, s + 18.0, -(HALF + 0.8), 1.0)
    ell = street.planter_shape(heading)
    for s in np.arange(26.0, LEN - 10.0, 47.0):
        if promenade_width(s) < 9.0 or s_mark - 75.0 < s < s_mark + 25.0:      # (nothing in front of the name letters)
            continue
        street.planter(kit, s, HALF + 5.4, ell, promenade.buffer(-0.3))
    for s in np.arange(9.0, LEN - 5.0, 23.5):
        w = promenade_width(s)
        if w < 6.0 or s_mark - 18.0 < s < s_mark + 8.0:
            continue
        x, z, ux, uz = pose(s, HALF + w - 1.7)
        if promenade.contains(Point(x, z)):
            street.bench(kit, x, z, ux, uz)
    for s in np.arange(60.0, LEN - 20.0, 94.0):            # a timber shelter with a bench under it
        w = promenade_width(s)
        if w < 11.0 or s_mark - 75.0 < s < s_mark + 25.0:
            continue
        x, z, ux, uz = pose(s, HALF + w * 0.66)
        if not promenade.buffer(-2.5).contains(Point(x, z)):
            continue
        street.shelter(kit, x, z, ux, uz)
    for k, s in enumerate(np.arange(start % 85.0 + 30.0, LEN - 10.0, 85.0)):          # signs for the driver, on the sea side, facing back along the road
        street.road_sign(kit, s, HALF + 0.95, [1, 2, 3, 0][k % 4])
    if not legacy:                                         # and for the driver coming the other way, on the shop side
        back = kit.along(LineString(list(centre.coords)[::-1]))
        for k, s in enumerate(np.arange(55.0, LEN - 10.0, 85.0)):
            x, z, _, _ = back.pose(s, HALF + 1.0)
            if not alley_area.buffer(1.0).contains(Point(x, z)):
                street.road_sign(back, s, HALF + 1.0, [1, 3, 2, 0][k % 4])
    for s in np.arange(18.0, LEN, 22.0):                   # gutter grates, both sides
        for off in (HALF - 0.2, -(HALF - 0.2)):
            street.grate(kit, s + (7.0 if off < 0 else 0.0), off)
    # asphalt repairs: patches across a lane and one long trench line, in newer, darker asphalt
    for k in range(9):
        s, off, ln, wd = rng.uniform(10.0, LEN - 20.0), rng.choice([1.6, -1.7, 1.2, -1.3]), rng.uniform(1.5, 6.0), rng.uniform(0.9, 2.4)
        street.patch(kit, s, off, ln, wd, inner)
    street.trench(kit, start + 130.0, start + 215.0, 0.95, 0.3)
    # two zebra crossings over the beach road: red surfacing, white bars, stop lines
    crossings = (start + 118.0, start + 318.0)
    for s in crossings:
        street.zebra(kit, s)
    # what comes with a crossing: a signal on a mast arm beyond it for each approach, a pedestrian head at each kerb, and the
    # diamond painted on the lane ahead of it
    for s in crossings:
        street.signal(kit, s + 5.9, 1.0)
        street.signal(kit, s - 1.3, -1.0)
        street.walk_signal(kit, s + 2.3, 1.0)
        street.walk_signal(kit, s + 2.3, -1.0)
        for d, off in ((-34.0, HALF / 2 - 0.1), (-54.0, HALF / 2 - 0.1), (38.6, -(HALF / 2 - 0.1)), (58.6, -(HALF / 2 - 0.1))):
            if 5.0 < s + d < LEN - 5.0:
                street.diamond(kit, s + d, off)
    # cabinets (traffic control, telecom) on the town-side sidewalk
    for s in (start + 112.0, start + 236.0, start + 392.0):
        x, z, ux, uz = pose(s, -(HALF + 0.75))
        if sidewalk.contains(Point(x, z)):
            street.cabinet(kit, x, z, ux, uz)

    # ---- the landmark: "안녕, 광안리" as on the real beach (the user's photo and correction, 2026-11-11): bold square-cut
    # letters in red, standing on the sand, parallel to the road and facing it, enlarged so they are seen from the driver's seat.
    # Tried before and dropped: white Latin letters (lost against the skyline), free-standing blue Hangul (strokes in the air),
    # white-on-blue slabs (a name plate), rounded handwriting turned toward the driver (not what stands there).
    TALL, DEPTH, HEAVY, STRUT, TRACK = 5.0, 0.6, 0.008, 0.16, 0.10
    word, legs, loose = landmark.lettering('안녕, 광안리', '안녕광안리', TALL, HEAVY, STRUT, TRACK)
    total = word.bounds[2]
    cx0, cz0, ux, uz = pose(s_mark, HALF + promenade_width(s_mark) + 7.0)      # on the sand, 7 m past the promenade's edge
    foot_top = SAND_TOP + 0.15
    landmark.sculpture(kit, word, cx0, cz0, ux, uz, foot_top, DEPTH, (0.90, 0.10, 0.06), (0.62, 0.05, 0.04))
    ends = [Point(cx0 + ux * e, cz0 + uz * e) for e in (-total / 2, total / 2)]
    print('landmark: %.1f m long, %.1f m tall, %.0f m from the road centre, %.0f-%.0f m from the water, on the sand: %s; pieces per syllable %s, legs %d'
          % (total, word.bounds[3], centre.distance(Point(cx0, cz0)), min(e.distance(water) for e in ends), max(e.distance(water) for e in ends),
             all(sand_all.contains(e) for e in ends), loose, legs))

    # ---- buildings: modelled beside the road, boxes with a window texture farther away, on the real footprints
    grid = terrain.Grid(DATA / 'BusanTerrain.json')
    buildings = osm('busan-slice-buildings-osm.json')
    if not legacy:
        net = json.loads((DATA / 'LandmarkNetwork.json').read_text(encoding='utf-8'))
        region = Polygon(net['regions']['gwangalli'])
        buildings = [e for e in buildings if len(e.get('geometry', [])) >= 3
                     and region.contains(Polygon([proj(p['lat'], p['lon']) for p in e['geometry']]).buffer(0).representative_point())]
    modelled, boxes = frontage.footprints(kit, buildings, road_main, alley_area, land_side, sea_side, grid.height, 48.0, 24.0)

    # ---- the far shore: flat land from the drive map's ground grid, hills from the terrain grid, the bridge
    land_all = terrain.ground_land(DATA / 'BusanSliceGround.json')
    far = land_all.simplify(10.0).difference(sea_side).difference(road_main.buffer(1.0)).difference(land_side)
    if legacy:
        terrain.far_land(kit, far)
        hills = terrain.hills(kit, grid, (1000, -2500, 11000, 9500), 30.0, 700.0, 6.0)
        route = json.loads((DATA / 'BusanSliceRoute.json').read_text(encoding='utf-8'))
        deck = LineString([(p['x'], p['z']) for p in route['points'] if p['k'] == 2])
        bridge.silhouette(kit, deck, [(t['x'], t['z']) for t in route['towers']], DECK_Y, DECK_DEPTH, DECK_W, TOWER_Y)
    else:
        # the district's own ground behind the yards, out to the edge of its region and no further
        hills = 0
        behind = region.difference(sea_side).difference(road_main.buffer(1.0)).difference(land_side).difference(centre.buffer(45.0))
        kit.M['yard'].polygon(behind, lambda arr: np.full(len(arr), BASE - 0.02))

    # ---- cars standing in the road
    # (in the map the player drives the shop-side lane, and cars have no collision: nothing may stand in that lane)
    cars = [street.car(kit, start + d, off, back, name) for d, off, back, name in CARS if legacy]      # (and moving cars drive the other lane)

    # ---- camera views: the driver's eye in the lane on the sea side (the game camera's 62 degrees)
    vs = [views.look(kit, 'D%03d_driver' % d, start + d, 0.0) for d in (40, 100, 160, 280, 400)]
    vs.append(views.look(kit, 'L160_glance_left', start + 160, -38.0))
    vs.append(views.look(kit, 'L290_glance_left', start + 290, -55.0))
    vs.append(views.look(kit, 'G280_glance_right', start + 280, 50.0))
    vs.append(views.look(kit, 'K120_kerb_close', start + 120, 24.0, 12.0, 1.2))
    vs.append(views.look(kit, 'M130_landmark', start + 130, 10.0))
    vs.append(views.look(kit, 'M200_landmark_near', start + 200, 22.0))
    vs.append(views.look(kit, 'M235_landmark_beside', start + 235, 60.0))
    vs.append(views.look(kit, 'M257_landmark_front', start + 257, 100.0))
    vs.append(views.above(kit, 'T250_from_above', start + 250, -70.0, 120, 120, 110, 90.0, 55))
    if not legacy:
        # the same thirteen kinds of view for the map's direction: in from the Haeundae end, the sea and the letters on the left
        back = kit.along(LineString(list(centre.coords)[::-1]))
        vs = [views.look(back, 'D%03d_driver' % d, d, 0.0) for d in (40, 140, 240, 340, 440, 560)]
        mark = LEN - s_mark                                # the letters, measured from the Haeundae end
        vs.append(views.look(back, 'L200_glance_left', 200, -45.0))
        vs.append(views.look(back, 'R200_glance_right', 200, 45.0))
        vs.append(views.look(back, 'R420_glance_right', 420, 55.0))
        vs.append(views.look(back, 'K300_kerb_close', 300, 24.0, 12.0, 1.2))
        vs.append(views.look(back, 'M_landmark_120_before', mark - 120.0, -8.0))
        vs.append(views.look(back, 'M_landmark_045_before', mark - 45.0, -30.0))
        vs.append(views.look(back, 'M_landmark_beside', mark + 4.0, -92.0))
        vs.append(views.above(kit, 'T250_from_above', start + 250, -70.0, 120, 120, 110, 90.0, 55))

    print('road %.0f m (the 500 m start at %.0f), side-street area %.0f m2, promenade %.0f m2, sand %.0f m2' % (LEN, start, alley_area.area, promenade.area, sand.area))
    print('buildings modelled %d, boxes %d, hill cells %d, cars %d' % (modelled, boxes, hills, len(cars)))
    scene = {'note': NOTE, 'heading': heading, 'sunYaw': 0.0, 'sunPitch': 38.0,
             'probe': [round(v, 2) for v in (pose(start + 200, 0.0)[0], ROAD_Y + 2.0, pose(start + 200, 0.0)[1])],
             'cars': cars, 'views': vs}
    # the reflection probes of output.district: here the one point the legacy JSON calls `probe` (2 m above the centre line at s=200)
    scene['probes'] = [{'name': 'S200', 'pos': scene['probe']}]
    return kit, scene
