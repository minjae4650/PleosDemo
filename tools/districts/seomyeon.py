"""Seomyeon, the town centre the two routes meet in: an eight-lane boulevard walled in by shop buildings and offices.

What says "Seomyeon" from the driver's seat: no sea, no sky line of hills; a wide road between unbroken rows of buildings of
every height, shop signs on each of them from the pavement to the roof, a few glass offices, guide boards for the station and
the tunnel. Before it the coast road from Gwangalli (B2) has a row of low buildings on its town side, and behind the tunnel road
(R1) the town thins out against the hill. No building is a copy of a real one; signs are generic trade words.

Roads, kerbs, sidewalks, flat ground and the driving surfaces are districts/ring.py's (segments B2, C1, S, T, R1)."""
import json
import math

import numpy as np
from shapely.geometry import LineString, Polygon
from shapely.ops import unary_union

from busan_kit import frontage, guide, street, towers
from busan_kit.geo import DATA
from busan_kit.kit import Kit
from busan_kit.materials import MAT
from busan_kit.mesh import flat
from districts.haeundae import street_view
from districts.ring import Road

NET = DATA / 'LandmarkNetwork.json'
NOTE = 'Generated by tools/districts/seomyeon.py from tools/network.py.'
SEED = 1114
ROAD_Y, KERB = 4.0, 0.16
BASE = ROAD_Y + KERB
GLASS = [(0.80, 0.90, 0.98), (0.92, 0.94, 0.96), (0.78, 0.92, 0.90), (1.0, 0.95, 0.86), (0.72, 0.80, 0.92)]


def build(tex_dir=None):
    if tex_dir is not None:
        guide.make_guide(tex_dir)
        towers.make_tower_textures(tex_dir)
    net = json.loads(NET.read_text(encoding='utf-8'))
    O, EA, EB = np.array(net['frame']['origin']), np.array(net['frame']['a']), np.array(net['frame']['b'])

    def W(a, b):
        p = O + EA * a + EB * b
        return (float(p[0]), float(p[1]))

    def AB(xz):
        d = np.asarray(xz, dtype=float) - O
        return float(d @ EA), float(d @ EB)
    heading = math.atan2(EA[1], EA[0])
    kit = Kit(dict(MAT, **guide.MATERIAL, **towers.MATERIAL), SEED, ROAD_Y, KERB, 14.5)
    M, rng = kit.M, kit.rng
    roads = {s['id']: Road(s) for s in net['segments']}
    b2, c1, sm, r1 = roads['B2'], roads['C1'], roads['S'], roads['R1']
    a_s, b_top = AB(c1.xz[0])                                 # the boulevard: a = a_s, from b_top down to the tunnel road
    _, b_back = AB(r1.xz[0])
    a_pw, _ = AB(r1.xz[-1])                                   # the tunnel's mouth
    boulevard = LineString([W(a_s, b_top), W(a_s, b_back - 60.0)])       # C1 and S in one line, carried on past the junction T
    L = (b_top - b_back)                                      # to the middle of T
    ks = kit.along(boulevard, 14.5)
    kb = kit.along(LineString(b2.xz), 6.5)
    kr = kit.along(LineString([W(a_s - 150.0, b_back), W(a_pw, b_back)]), 6.5)       # the tunnel road, carried back across T
    r_off = 150.0                                             # where the boulevard's centre line crosses it
    every_road = unary_union([LineString(r.xz).buffer(max(r.right, -r.left) + 5.2) for r in roads.values()])
    hill = Polygon(net['regions']['hill']).intersection(Polygon([W(a_pw + 0.4, -1000), W(600, -1000), W(600, -300), W(a_pw + 0.4, -300)])).buffer(10.0)
    gwangalli = Polygon(net['regions']['gwangalli']).buffer(2.0)
    taken = []

    def plot(k, s0, s1, d0, d1):
        return Polygon([k.pose(s0, d0)[:2], k.pose(s1, d0)[:2], k.pose(s1, d1)[:2], k.pose(s0, d1)[:2]]).buffer(0)

    def free(p):
        return not any(p.intersects(q) for q in taken) and not p.intersects(hill) and not p.intersects(gwangalli) and not p.buffer(-0.3).intersects(every_road)

    def shop(k, s0, s1, side, line_off, storeys, depth=26.0):
        base = plot(k, s0, s1, side * line_off, side * (line_off + depth))
        if not free(base):
            return False
        taken.append(base)
        frontage.building(k, base, storeys, True)
        return True

    def office(k, s0, s1, side, line_off, height, depth=34.0, lobes=0):
        """A podium of shops and a glass office on it."""
        base = plot(k, s0, s1, side * line_off, side * (line_off + depth))
        if not free(base):
            return
        taken.append(base)
        frontage.building(k, base, 3, True)
        cx, cz, ux, uz = k.pose((s0 + s1) / 2, side * (line_off + depth / 2))
        shape = towers.rounded(cx, cz, (s1 - s0) / 2 - 3.0, depth / 2 - 3.5, math.atan2(uz, ux), lobes or 4, 0.04)
        towers.glass_tower(kit, shape, BASE + 4.2 + 2 * frontage.FLOOR + 0.9, BASE + height, rng.choice(GLASS), crown=0.06)

    def row(k, s_from, s_to, side, line_off, heights, offices=(), depth=26.0, gap=1.2):
        """An unbroken row: lots of 14-30 m, each its own building, storeys drawn from `heights`."""
        s = s_from
        while s < s_to - 12.0:
            w = min(rng.uniform(14.0, 30.0), s_to - s)
            tall = next((h for s_at, h in offices if s <= s_at < s + w), None)
            if tall:
                w = min(max(w, 34.0), s_to - s)
                office(k, s, s + w - gap, side, line_off, tall, depth + 8.0)
            else:
                shop(k, s, s + w - gap, side, line_off, rng.choice(heights), depth)
            s += w

    # ---- the boulevard: both sides built up from the junction J to the junction T
    LINE = 14.5 + 5.2
    row(ks, 46.0, L - 34.0, 1.0, LINE, [5, 6, 8, 9, 10, 12, 14, 16, 9, 7], offices=((150.0, 96.0), (385.0, 128.0)))
    row(ks, 46.0, L + 44.0, -1.0, LINE, [6, 7, 8, 10, 11, 13, 15, 18, 8, 5], offices=((250.0, 112.0), (470.0, 88.0)))
    # the end of the boulevard: what the driver looks at down its whole length, across the junction T
    row(kr, 6.0, r_off + 26.0, -1.0, 6.5 + 5.2, [9, 12, 14, 16, 11], offices=((r_off - 2.0, 140.0),), depth=28.0)
    # the tunnel road: lower buildings to the hill on both sides
    row(kr, r_off + 44.0, kr.LEN - 8.0, 1.0, 6.5 + 5.2, [4, 5, 6, 8, 5, 3], depth=22.0)
    row(kr, r_off + 30.0, kr.LEN - 8.0, -1.0, 6.5 + 5.2, [5, 6, 8, 10, 4], depth=22.0)
    # the coast road from Gwangalli: a row on the town side
    row(kb, 4.0, kb.LEN - 96.0, 1.0, 6.5 + 5.2, [3, 4, 5, 6, 4, 8, 3], depth=20.0)

    lawn = Polygon([ks.pose(s, 1.05)[:2] for s in np.arange(30.0, L - 40.0, 6.0)] + [ks.pose(s, -1.05)[:2] for s in np.arange(30.0, L - 40.0, 6.0)][::-1]).buffer(0)
    M['grass'].polygon(lawn, flat(BASE + 0.03))
    for s in np.arange(40.0, L - 36.0, 36.0):
        street.lamp(ks, s, 14.5 + 0.9, -1.0)
        street.lamp(ks, s + 18.0, -(14.5 + 0.9), 1.0)
    for s in np.arange(r_off + 40.0, kr.LEN - 10.0, 34.0):
        street.lamp(kr, s, 6.5 + 0.9, -1.0)
    for s in np.arange(20.0, kb.LEN - 90.0, 36.0):
        street.lamp(kb, s, 6.5 + 0.9, -1.0)

    # ---- over the road: where this is, and which way the tunnel and Haeundae are; crossings and signals
    def gantry(k, s, o0, o1, boards):
        x0, z0, ux, uz = k.pose(s, o0)
        x1, z1, _, _ = k.pose(s, o1)
        for x, z in ((x0, z0), (x1, z1)):
            M['metal'].frustum(x, z, 0.17, 0.15, BASE, BASE + 7.7, 10)
        cx, cz = (x0 + x1) / 2, (z0 + z1) / 2
        rx, rz = uz, -ux
        for y, hw in ((BASE + 7.45, 0.15), (BASE + 6.25, 0.11)):
            M['metal'].obox(cx, cz, rx, rz, abs(o1 - o0) / 2, hw, y - hw, y + hw, (1.0, 1.0, 1.0), bottom=True)
        for key, off, width in boards:
            bx, bz, _, _ = k.pose(s, off)
            guide.board(kit, key, (bx - ux * 0.3, BASE + 6.85, bz - uz * 0.3), (rx, rz), width, width / 3)
    gantry(ks, 120.0, 0.6, 15.6, (('seomyeon', 4.4, 5.4), ('seomyeon_station', 10.9, 5.4)))
    gantry(ks, L - 150.0, 0.6, 15.6, (('seomyeon_ahead', 4.4, 5.0), ('haeundae_right', 10.9, 5.6)))
    gantry(kr, r_off + 70.0, -0.6, 7.6, (('tunnel', 1.3, 3.6), ('haeundae_ahead', 5.0, 3.6)))
    for s in (64.0, 300.0, L - 52.0):
        street.zebra(ks, s)
        street.signal(ks, s + 8.0, 1.0)
        street.walk_signal(ks, s + 2.3, 1.0)
        street.walk_signal(ks, s + 2.3, -1.0)
    for s in (200.0, 420.0):
        for off in (3.125, 6.375, 9.625, 12.875):
            street.arrow(ks, s, off)

    # ---- cars: waiting at the crossings in the oncoming lanes, and parked at the kerb. Cars have no collision and the player
    # drives the forward lanes, so none stands in a forward lane except against the kerb (the routes use the third lane of four)
    names = ('Hyundai_Tucson_White', 'Hyundai_Azera_Silver', 'Hyundai_i30_Blue', 'Hyundai_Tucson_Graphite', 'Hyundai_Azera_Navy', 'Hyundai_i30_Black', 'Hyundai_Tucson_Black', 'Hyundai_i30_Burgundy', 'Hyundai_Porter_II_Blue', 'Generic_DeliveryTruck')
    cars = []
    for s in (64.0, 300.0, L - 52.0):
        for lane in (-6.375, -9.625, -12.875):                # (the lane by the median is the moving cars')
            d = s + 9.6 + rng.uniform(0.0, 1.5)
            for _ in range(rng.choice([1, 2, 3, 4])):
                cars.append(street.car(ks, d, lane + rng.uniform(-0.2, 0.2), True, rng.choice(names[:8])))
                d += rng.uniform(6.4, 8.5)
    for s in (96.0, 104.5, 176.0, 232.0, 240.0, 356.0, 448.0, 456.5):
        cars.append(street.car(ks, s, 13.35, False, rng.choice(names)))
    for s in (140.0, 148.0, 270.0, 395.0, 403.0, 498.0):
        cars.append(street.car(ks, s, -13.35, True, rng.choice(names)))

    # ---- behind and beyond: the town, plain blocks thinning out with distance, and a few glass offices among them
    def scatter(a0, a1, b0, b1_, count, tall=False):
        for _ in range(count):
            a, b = rng.uniform(a0, a1), rng.uniform(b0, b1_)
            x, z = W(a, b)
            if tall:
                shape = towers.rounded(x, z, rng.uniform(13, 19), rng.uniform(10, 14), rng.uniform(0, math.pi), 4, 0.04)
            else:
                w, d, t = rng.uniform(16, 36), rng.uniform(12, 22), rng.choice([0.0, math.pi / 2]) + heading
                shape = Polygon([(x + math.cos(t) * i * w / 2 - math.sin(t) * j * d / 2, z + math.sin(t) * i * w / 2 + math.cos(t) * j * d / 2) for i, j in ((-1, -1), (1, -1), (1, 1), (-1, 1))])
            if not free(shape.buffer(5.0)):
                continue
            taken.append(shape)
            if tall:
                towers.glass_tower(kit, shape, BASE - 0.1, BASE + rng.uniform(70, 150), rng.choice(GLASS), crown=0.06)
            else:
                frontage.block(kit, shape, rng.choice([5, 6, 8, 10, 12, 15, 18, 20]), BASE - 0.1)
    scatter(a_s + 46, a_pw - 6, b_back + 36, b_top - 30, 70)                # between the boulevard and the hill
    scatter(a_s + 46, a_pw - 6, b_back + 36, b_top - 30, 5, True)
    scatter(a_s - 330, a_s - 48, b_back - 40, b_top + 6, 110)               # west of the boulevard
    scatter(a_s - 330, a_s - 48, b_back - 40, b_top - 40, 8, True)
    scatter(a_s - 900, a_s - 330, b_back - 500, b_top + 40, 150)            # further west, out to the horizon
    scatter(a_s - 700, a_s - 330, b_back - 400, b_top - 100, 10, True)
    scatter(a_s - 500, a_pw + 300, b_back - 600, b_back - 44, 150)          # behind the end of the boulevard

    # ---- views, reflections
    vs = [street_view(ks, 'D%03d_driver' % d, d, 9.625) for d in (20, 120, 220, 320, 420, 520)]
    vs.append(street_view(ks, 'L220_glance_left', 220, 9.625, -50.0))
    vs.append(street_view(ks, 'R220_glance_right', 220, 9.625, 50.0))
    vs.append(street_view(ks, 'U320_up', 320, 9.625, 20.0, lift=22.0))
    vs.append(street_view(ks, 'K250_kerb_close', 250, 12.875, 24.0, dist=12.0))
    vs.append(street_view(kb, 'B2_040_driver', 40, 1.625))
    vs.append(street_view(kb, 'B2_150_driver', 150, 1.625))
    vs.append(street_view(kr, 'R1_050_driver', r_off + 50.0, 4.875))
    mid = ks.pose(L / 2, 6.0)
    probes = [{'name': 'Boulevard', 'pos': [mid[0], ROAD_Y + 2.0, mid[1]], 'importance': 1}]
    scene = {'note': NOTE, 'heading': heading, 'sunYaw': 0.0, 'sunPitch': 38.0, 'probe': probes[0]['pos'], 'probes': probes, 'cars': cars, 'views': vs}
    return kit, scene
