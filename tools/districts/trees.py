"""Street trees: a row along the sidewalks of the boulevards, the coast road from Gwangalli, the tunnel road and the streets of the
infill, 1.9 m in from the kerb, about 9 m apart, clear of posts, junctions and doorways' signs.

Each tree is four crossed picture cards (busan_kit: one quad each, seen from both sides by the FoliageCards shader) cut from a
four-view atlas that BusanLandmarkTrees.cs renders from a downloaded model (Poly Haven "Jacaranda Tree", CC0). The atlas and its
.txt (panel size and the model's height, in metres) are in TEX_DIR; without them this district is empty.

It builds after the others: it reads ring's tree line and every district's posts and footprints from footprints.json."""
import json
import math

import numpy as np
from shapely.geometry import Point, shape
from shapely.ops import unary_union
from shapely.prepared import prep

from busan_kit.geo import DATA
from busan_kit.kit import Kit
from busan_kit.materials import TEX, TEX_DIR, surface
from busan_kit.mesh import lines

NET = DATA / 'LandmarkNetwork.json'
OUT = r'C:\c\busan-out'
NOTE = 'Generated by tools/districts/trees.py. Tree pictures from Poly Haven "Jacaranda Tree" (CC0).'
SEED = 1116
ROAD_Y, KERB = 4.0, 0.16
BASE = ROAD_Y + KERB
ATLAS = 'tree_jacaranda.png'
SPACING = 10.0
MATERIAL = {'tree': dict(surface(TEX + ATLAS, '', (1.0, 1.0, 1.0), 0.0), kind='foliage')}


def read(name):
    try:
        return json.loads(open('%s\\%s\\footprints.json' % (OUT, name), encoding='utf-8').read())
    except FileNotFoundError:
        return None


def build(tex_dir=None):
    net = json.loads(NET.read_text(encoding='utf-8'))
    EA = np.array(net['frame']['a'])
    heading = math.atan2(EA[1], EA[0])
    kit = Kit(dict(MATERIAL), SEED, ROAD_Y, KERB, 6.5)
    M, rng = kit.M, kit.rng
    meta = TEX_DIR / (ATLAS + '.txt')
    scene = {'note': NOTE, 'heading': heading, 'sunYaw': 0.0, 'sunPitch': 38.0, 'probe': [0.0, 6.0, 0.0], 'probes': [], 'cars': [], 'views': []}
    if not meta.exists():
        print('trees: no %s (bake it with the bridge command treebake)' % meta)
        return kit, scene
    panel, _, model_h = (float(v) for v in meta.read_text().split())
    ring = read('ring')
    if not ring or not ring.get('treeline'):
        raise SystemExit('build the ring district first')
    treeline = shape(ring['treeline'])
    posts, placed, zebras = [], [], []
    for name in ('ring', 'gwangalli', 'bridge', 'haeundae', 'seomyeon', 'infill'):
        data = read(name)
        if data:
            posts += data.get('posts', [])
            placed += [shape(p) for p in data['placed']]
            zebras += data.get('zebras', [])
    keep_off = unary_union([Point(x, z).buffer(2.6) for x, z in posts] + [p.buffer(1.0) for p in placed] +
                           [Point(j['at']).buffer(30.0) for j in net['junctions']] +
                           [Point(zb[0], zb[1]).buffer(34.0) for zb in zebras])     # the signal heads over a crossing stay in sight
    clear = prep(keep_off)
    count = 0
    for part in lines(treeline):
        if part.length < 20.0:
            continue
        d = rng.uniform(2.0, SPACING)
        while d < part.length - 2.0:
            p = part.interpolate(d)
            d += SPACING + rng.uniform(-1.0, 1.0)
            if clear.contains(p):
                continue
            h = rng.uniform(6.5, 9.0)
            scale = h / model_h
            size = panel * scale
            turn = rng.uniform(0.0, math.pi)
            tint = rng.uniform(0.82, 1.02)
            col = (tint, tint * rng.uniform(0.97, 1.03), tint * rng.uniform(0.9, 1.0))
            for k in range(4):
                phi = turn + k * math.pi / 4
                rx, rz = math.cos(phi), -math.sin(phi)
                x0, z0 = p.x - rx * size / 2, p.y - rz * size / 2
                x1, z1 = p.x + rx * size / 2, p.y + rz * size / 2
                y0, y1 = BASE - 0.05, BASE - 0.05 + size
                u0, u1 = k / 4.0, (k + 1) / 4.0
                M['tree'].quad((x0, y0, z0), (x1, y0, z1), (x1, y1, z1), (x0, y1, z0), (math.sin(phi), 0.0, math.cos(phi)),
                               ((u0, 0.0), (u1, 0.0), (u1, 1.0), (u0, 1.0)), col)
            count += 1
    # the wooded hill inside the loop (places from districts/ring.py): two crossed cards a tree, darker and more varied than the
    # street trees, so the slope reads as woods and not as rows
    wood = 0
    for x, y, z, h in ring.get('forest') or []:
        scale = h / model_h
        size = panel * scale
        turn = rng.uniform(0.0, math.pi)
        tint = rng.uniform(0.50, 0.80)
        col = (tint * rng.uniform(0.86, 1.0), tint, tint * rng.uniform(0.72, 0.92))
        v = rng.randrange(4)
        for k in range(2):
            phi = turn + k * math.pi / 2
            rx, rz = math.cos(phi), -math.sin(phi)
            x0, z0 = x - rx * size / 2, z - rz * size / 2
            x1, z1 = x + rx * size / 2, z + rz * size / 2
            u0, u1 = ((v + k) % 4) / 4.0, ((v + k) % 4 + 1) / 4.0
            M['tree'].quad((x0, y, z0), (x1, y, z1), (x1, y + size, z1), (x0, y + size, z0), (math.sin(phi), 0.0, math.cos(phi)),
                           ((u0, 0.0), (u1, 0.0), (u1, 1.0), (u0, 1.0)), col)
        wood += 1
    print('trees: %d along %.0f m of sidewalk, %d on the hill' % (count, treeline.length, wood))
    return kit, scene
