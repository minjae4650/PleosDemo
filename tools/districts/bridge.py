"""Gwangan Bridge as the driver crosses it: the two ramps and the suspension span of tools/network.py (A1, A2, A3), dressed.

What makes it the bridge from the driver's seat: passing between the legs of two tall portal towers, the main cables sweeping
down to the deck and up again, the hangers going by in a rhythm, the sea on both sides. From the beach it is the long truss
between two towers. Only that structure is kept; sizes are the network's (a 600 m span, a deck 30 m up, towers 100 m), not
the real ones (the real main span is 500 m between towers 116 m high). The real bridge has two decks and the west-bound one
runs inside the truss; here the car takes the open top, because that is the view people know.

Nothing is copied from a photograph. The driving surfaces are made by districts/ring.py."""
import json
import math

import numpy as np

from busan_kit import guide
from busan_kit.geo import DATA
from busan_kit.kit import Kit
from busan_kit.materials import MAT
from districts.ring import Road

NET = DATA / 'LandmarkNetwork.json'
NOTE = 'Generated by tools/districts/bridge.py from tools/network.py.'
SEED = 1112
ROAD_Y, KERB = 4.0, 0.16
BASE = ROAD_Y + KERB
TOWER_TOP = 100.0
TRUSS = 8.5                       # depth of the stiffening truss under the deck
GIRDER = 2.2                      # depth of the ramps' box girder
WHITE, CONCRETE, SHADE, STEEL = (0.90, 0.90, 0.88), (0.76, 0.76, 0.74), (0.52, 0.52, 0.53), (0.80, 0.82, 0.84)
RAIL = (0.70, 0.72, 0.74)


def unit(v):
    v = np.asarray(v, dtype=float)
    return v / np.linalg.norm(v)


def build(tex_dir=None):
    if tex_dir is not None:
        guide.make_guide(tex_dir)
    net = json.loads(NET.read_text(encoding='utf-8'))
    kit = Kit(dict(MAT, **guide.MATERIAL), SEED, ROAD_Y, KERB, 3.5)
    M = kit.M
    roads = {s['id']: Road(s) for s in net['segments']}
    a1, a2, a3 = roads['A1'], roads['A2'], roads['A3']
    deck = float(net['deckY'])
    heading = math.atan2(net['frame']['a'][1], net['frame']['a'][0])
    for r in (a1, a2, a3):
        r.s = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(r.xz, axis=0), axis=1))])

    def ease(v):
        v = max(0.0, min(1.0, v))
        return v * v * (3 - 2 * v)
    wide, narrow = a2.right, a1.right                       # outer edge of the lanes: four on the span, two on the ramps
    edge = {a1.id: [narrow + (wide - narrow) * ease((s - (a1.s[-1] - 110.0)) / 100.0) for s in a1.s],
            a2.id: [wide] * a2.n,
            a3.id: [wide - (wide - narrow) * ease((s - 10.0) / 100.0) for s in a3.s]}
    LEFT = a2.median / 2 - 0.5                               # inner face of the left barrier; the right one is 0.5 m past the lanes

    def P(r, i, off, dy=0.0):
        q = r.xz[i] + r.r[i] * off
        return (float(q[0]), float(r.y[i] + dy), float(q[1]))

    def band(mesh, r, f0, f1, dy=0.0, i0=0, i1=None, col=(1, 1, 1), up=True, every=1, phase=0):
        i1 = r.n if i1 is None else i1
        out = (0.0, 1.0, 0.0) if up else (0.0, -1.0, 0.0)
        for i in range(i0, i1 - 1):
            if every > 1 and (i + phase) % every:
                continue
            mesh.quad(P(r, i, f0(i), dy), P(r, i + 1, f0(i + 1), dy), P(r, i + 1, f1(i + 1), dy), P(r, i, f1(i), dy), out, col=col)

    def sweep(mesh, r, prof, i0, i1, col):
        """A cross-section carried along the road: prof(i) gives its corners as (offset, height above the road)."""
        for i in range(i0, i1 - 1):
            pa, pb = prof(i), prof(i + 1)
            co, ch = sum(p[0] for p in pa) / len(pa), sum(p[1] for p in pa) / len(pa)
            for k in range(len(pa) - 1):
                (o0, h0), (o1, h1) = pa[k], pa[k + 1]
                n = (h1 - h0, -(o1 - o0))
                if n[0] * ((o0 + o1) / 2 - co) + n[1] * ((h0 + h1) / 2 - ch) < 0:
                    n = (-n[0], -n[1])
                out = (float(r.r[i][0] * n[0]), float(n[1]), float(r.r[i][1] * n[0]))
                mesh.quad(P(r, i, o0, h0), P(r, i, o1, h1), P(r, i + 1, pb[k + 1][0], pb[k + 1][1]), P(r, i + 1, pb[k][0], pb[k][1]), out, col=col)

    def strut(mesh, p0, p1, w, col):
        """A square bar between two points."""
        p0, p1 = np.array(p0, dtype=float), np.array(p1, dtype=float)
        d = unit(p1 - p0)
        u = unit(np.cross(d, (0.0, 1.0, 0.0) if abs(d[1]) < 0.95 else (1.0, 0.0, 0.0)))
        v = np.cross(d, u)
        c = [(u + v) * w / 2, (u - v) * w / 2, (-u - v) * w / 2, (-u + v) * w / 2]
        for k in range(4):
            a_, b_ = c[k], c[(k + 1) % 4]
            mesh.quad(tuple(p0 + a_), tuple(p0 + b_), tuple(p1 + b_), tuple(p1 + a_), tuple(a_ + b_), col=col)

    def tube(mesh, pts, radius, sides, col):
        """A round cable through the points; the rings share their corners, so it is shaded smooth."""
        pts = [np.array(p, dtype=float) for p in pts]
        first = len(mesh.v) // 3
        ring_pts = []
        for k, p in enumerate(pts):
            d = unit(pts[min(k + 1, len(pts) - 1)] - pts[max(k - 1, 0)])
            u = unit(np.cross(d, (0.0, 1.0, 0.0)))
            v = np.cross(d, u)
            ring_pts += [tuple(p + (u * math.cos(2 * math.pi * j / sides) + v * math.sin(2 * math.pi * j / sides)) * radius) for j in range(sides)]
        mesh._add(ring_pts, [(0.0, 0.0)] * len(ring_pts), col)
        a_, b_, c_ = np.array(ring_pts[0]), np.array(ring_pts[sides]), np.array(ring_pts[1])
        outward = float(np.cross(b_ - a_, c_ - a_) @ (a_ - pts[0])) > 0
        for k in range(len(pts) - 1):
            for j in range(sides):
                j1 = (j + 1) % sides
                q0, q1, q2, q3 = first + k * sides + j, first + (k + 1) * sides + j, first + (k + 1) * sides + j1, first + k * sides + j1
                mesh.t += [q0, q1, q3, q1, q2, q3] if outward else [q0, q3, q1, q1, q3, q2]

    def block(mesh, r, i, o0, o1, along0, along1, y0, y1, col, taper=1.0):
        """A box set square to the road at point i: across from o0 to o1, along from along0 to along1 (metres past i)."""
        c = r.xz[i] + r.r[i] * (o0 + o1) / 2 + r.t[i] * (along0 + along1) / 2
        hl, hw = (along1 - along0) / 2, abs(o1 - o0) / 2
        if taper == 1.0:
            mesh.obox(float(c[0]), float(c[1]), float(r.t[i][0]), float(r.t[i][1]), hl, hw, y0, y1, col, 3.0, bottom=True)
            return
        t_, s_ = r.t[i], r.r[i]
        lo = [c + t_ * a * hl + s_ * b * hw for a, b in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
        hi = [c + t_ * a * hl * taper + s_ * b * hw * taper for a, b in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
        for k in range(4):
            k1 = (k + 1) % 4
            out = (lo[k] + lo[k1]) / 2 - c
            mesh.quad((lo[k][0], y0, lo[k][1]), (lo[k1][0], y0, lo[k1][1]), (hi[k1][0], y1, hi[k1][1]), (hi[k][0], y1, hi[k][1]), (out[0], 0.0, out[1]), col=col)
        mesh.quad((hi[0][0], y1, hi[0][1]), (hi[1][0], y1, hi[1][1]), (hi[2][0], y1, hi[2][1]), (hi[3][0], y1, hi[3][1]), (0.0, 1.0, 0.0), col=col)

    # ---- the roadway: asphalt, lane lines, a steel joint where the span meets the ramps and at each tower
    tower_i = [int(np.argmin(np.linalg.norm(a2.xz - np.array(t), axis=1))) for t in net['bridge']['towers']]
    for r in (a1, a2, a3):
        e = edge[r.id]
        up0 = next((i for i in range(r.n) if r.y[i] > ROAD_Y + 0.02), 0)
        up1 = max((i for i in range(r.n) if r.y[i] > ROAD_Y + 0.02), default=r.n - 1) + 1
        i0, i1 = max(0, up0 - 2), min(r.n, up1 + 2)
        band(M['asphalt'], r, lambda i: LEFT, lambda i, e=e: e[i] + 0.5, 0.0, i0, i1)
        band(M['paint_white'], r, lambda i: LEFT + 0.35, lambda i: LEFT + 0.50, 0.008, i0, i1)
        band(M['paint_white'], r, lambda i, e=e: e[i] + 0.0, lambda i, e=e: e[i] + 0.15, 0.008, i0, i1)
        lanes = int(round((max(e) - r.median / 2) / r.lw))
        for k in range(1, lanes):
            o = r.median / 2 + k * r.lw
            j0 = next((i for i in range(i0, i1) if e[i] >= o + 1.6), None)
            j1 = max((i for i in range(i0, i1) if e[i] >= o + 1.6), default=None)
            if j0 is not None:
                band(M['paint_white'], r, lambda i, o=o: o - 0.06, lambda i, o=o: o + 0.06, 0.008, j0, j1 + 1, every=2)
    for i in [0, a2.n - 2] + tower_i:
        M['metal'].quad(P(a2, i, LEFT, 0.012), P(a2, i, wide + 0.5, 0.012),
                        tuple(np.array(P(a2, i, wide + 0.5, 0.012)) + np.array([a2.t[i][0], 0.0, a2.t[i][1]]) * 0.45),
                        tuple(np.array(P(a2, i, LEFT, 0.012)) + np.array([a2.t[i][0], 0.0, a2.t[i][1]]) * 0.45), (0.0, 1.0, 0.0), col=(0.9, 0.9, 0.9))

    # ---- barriers with a steel rail on top, the deck's edge and what carries it
    def barrier(side, off):
        # the road face first: a kerb step, the sloped face, the top, the outer face
        s = side
        return [(off, 0.0), (off - 0.06 * s, 0.10), (off - 0.18 * s, 0.34), (off - 0.24 * s, 0.86), (off - 0.42 * s, 0.86), (off - 0.45 * s, 0.0)]
    for r in (a1, a2, a3):
        e = edge[r.id]
        up = [i for i in range(r.n) if r.y[i] > ROAD_Y + 0.35]
        i0, i1 = up[0], up[-1] + 1
        sweep(M['stone'], r, lambda i: barrier(1.0, LEFT), i0, i1, CONCRETE)
        sweep(M['stone'], r, lambda i, e=e: barrier(-1.0, e[i] + 0.5), i0, i1, CONCRETE)
        for off_of, s in ((lambda i: LEFT - 0.33, 1.0), (lambda i, e=e: e[i] + 0.5 + 0.33, -1.0)):
            for h in (1.08, 1.30):                           # two rails
                sweep(M['painted'], r, lambda i, f=off_of, h=h: [(f(i) - 0.04, h - 0.04), (f(i) + 0.04, h - 0.04), (f(i) + 0.04, h + 0.04), (f(i) - 0.04, h + 0.04), (f(i) - 0.04, h - 0.04)], i0, i1, RAIL)
            for i in range(i0, i1, 1):                       # a post every 4 m
                p0, p1 = np.array(P(r, i, off_of(i), 0.86)), np.array(P(r, i, off_of(i), 1.32))
                strut(M['painted'], p0, p1, 0.07, RAIL)
        lo_edge = LEFT - 0.45
        if r is a2:
            # the span: a deep truss under the deck, seen from the beach as a lattice between two chords
            for off in (lo_edge + 0.6, wide + 0.95 - 0.6):
                for h in (-0.5, -TRUSS):
                    sweep(M['painted'], r, lambda i, off=off, h=h: [(off - 0.35, h - 0.35), (off + 0.35, h - 0.35), (off + 0.35, h + 0.35), (off - 0.35, h + 0.35), (off - 0.35, h - 0.35)], 0, r.n, STEEL)
                for k, i in enumerate(range(0, r.n - 3, 3)):
                    top0, bot0 = P(r, i, off, -0.5), P(r, i, off, -TRUSS)
                    top1, bot1 = P(r, i + 3, off, -0.5), P(r, i + 3, off, -TRUSS)
                    strut(M['painted'], top0, bot0, 0.45, STEEL)
                    strut(M['painted'], bot0 if k % 2 else top0, top1 if k % 2 else bot1, 0.45, STEEL)       # diagonals, leaning alternate ways
            band(M['stone'], r, lambda i: lo_edge, lambda i: wide + 0.95, -0.55, col=SHADE, up=False)
            band(M['stone'], r, lambda i: lo_edge + 0.3, lambda i: wide + 0.65, -TRUSS + 0.3, col=CONCRETE)       # the lower deck
            band(M['stone'], r, lambda i: lo_edge + 0.3, lambda i: wide + 0.65, -TRUSS - 0.3, col=SHADE, up=False)
            sweep(M['stone'], r, lambda i: [(lo_edge, 0.0), (lo_edge, -0.55)], 0, r.n, CONCRETE)
            sweep(M['stone'], r, lambda i: [(wide + 0.95, 0.0), (wide + 0.95, -0.55)], 0, r.n, CONCRETE)
        else:
            # a ramp: a concrete box girder with the slab reaching out past its webs, on single columns with a wide head
            def girder(i, e=e):
                o0, o1 = lo_edge, e[i] + 0.95
                return [(o0, 0.0), (o0, -0.35), (o0 + 1.3, -0.75), (o0 + 1.3, -GIRDER), (o1 - 1.3, -GIRDER), (o1 - 1.3, -0.75), (o1, -0.35), (o1, 0.0)]
            sweep(M['stone'], r, girder, i0, i1, CONCRETE)
            gap = 0.0
            for i in range(i0 + 1, i1 - 1):
                gap += float(r.s[i] - r.s[i - 1])
                clear = r.y[i] - GIRDER - BASE
                if clear < 2.6:                              # near the ground the ramp stands on walls
                    for off in (lo_edge + 1.3, e[i] + 0.95 - 1.3):
                        M['stone'].quad2(P(r, i, off, -GIRDER), P(r, i + 1, off, -GIRDER), (P(r, i + 1, off)[0], BASE - 0.3, P(r, i + 1, off)[2]), (P(r, i, off)[0], BASE - 0.3, P(r, i, off)[2]),
                                         (float(r.r[i][0]), 0.0, float(r.r[i][1])), col=CONCRETE)
                elif gap >= 40.0:
                    gap = 0.0
                    mid = (lo_edge + e[i] + 0.95) / 2
                    block(M['stone'], r, i, mid - 1.2, mid + 1.2, -1.0, 1.0, 0.0, float(r.y[i] - GIRDER - 1.5), CONCRETE)
                    block(M['stone'], r, i, lo_edge + 1.0, e[i] + 0.95 - 1.0, -1.1, 1.1, float(r.y[i] - GIRDER - 1.5), float(r.y[i] - GIRDER), CONCRETE)

    # ---- the two towers: tapering legs either side of the deck, tied by three beams, on a footing in the water
    cable_l, cable_r = LEFT - 0.45 - 2.4, wide + 0.95 + 2.4
    for i in tower_i:
        for off in (cable_l, cable_r):
            block(M['stone'], a2, i, off - 1.7, off + 1.7, -2.3, 2.3, 3.0, TOWER_TOP, WHITE, taper=0.72)
        for y0, y1 in ((deck - TRUSS - 7.0, deck - TRUSS - 2.5), (deck + 30.0, deck + 34.5), (TOWER_TOP - 9.0, TOWER_TOP - 3.5)):
            k = 1.0 - 0.28 * ((y0 + y1) / 2 - 3.0) / (TOWER_TOP - 3.0)      # the legs taper, so the beams get shorter with height
            block(M['stone'], a2, i, cable_l + 1.7 * k - 0.1, cable_r - 1.7 * k + 0.1, -1.5 * k, 1.5 * k, y0, y1, WHITE)
        block(M['stone'], a2, i, cable_l - 5.0, cable_r + 5.0, -7.0, 7.0, -1.0, 3.0, CONCRETE)
        for off in (cable_l, cable_r):                       # a saddle housing on each leg
            block(M['painted'], a2, i, off - 1.0, off + 1.0, -1.6, 1.6, TOWER_TOP, TOWER_TOP + 1.6, STEEL)

    # ---- main cables, hangers, and the arms that reach from the deck to the cable line
    s1, s2, L = float(a2.s[tower_i[0]]), float(a2.s[tower_i[1]]), float(a2.s[-1])
    if s1 > s2:
        s1, s2 = s2, s1
    saddle, low, end = TOWER_TOP + 0.8, deck + 5.5, deck + 2.6

    def cable_y(s):
        if s <= s1:
            u = s / s1
            return end + (saddle - end) * u - 4.0 * 3.0 * u * (1 - u)
        if s >= s2:
            u = (L - s) / (L - s2)
            return end + (saddle - end) * u - 4.0 * 3.0 * u * (1 - u)
        u = (s - s1) / (s2 - s1)
        return low + (saddle - low) * (2 * u - 1) ** 2
    for off in (cable_l, cable_r):
        pts = []
        for i in range(a2.n):
            q = a2.xz[i] + a2.r[i] * off
            pts.append((float(q[0]), cable_y(float(a2.s[i])), float(q[1])))
        tube(M['painted'], pts, 0.42, 8, WHITE)
        side = 1.0 if off < 8 else -1.0
        for i in range(3, a2.n - 3, 3):                      # a hanger every 12 m
            if min(abs(i - t) for t in tower_i) < 2:
                continue
            top = pts[i]
            if top[1] - deck < 1.2:
                continue
            foot = P(a2, i, off, -0.3)
            strut(M['painted'], foot, top, 0.14, STEEL)
            strut(M['painted'], foot, P(a2, i, off + side * 2.6, -0.3), 0.3, STEEL)
    for i, sign in ((0, -1.0), (a2.n - 1, 1.0)):             # anchor blocks at both ends, either side of the deck
        for o0, o1 in ((cable_l - 3.2, cable_l + 2.0), (cable_r - 2.0, cable_r + 3.2)):
            block(M['stone'], a2, i, o0, o1, -16.0 if sign < 0 else -10.0, 10.0 if sign < 0 else 16.0, 0.0, deck + 1.25, CONCRETE)
        block(M['stone'], a2, i, cable_l - 3.2, cable_r + 3.2, -9.0, 9.0, 0.0, deck - TRUSS - 0.4, CONCRETE)

    # ---- lamps: a pole on the barrier with a short arm over the road
    def lamp(r, i, off, side):
        foot = np.array(P(r, i, off, 0.86))
        top = foot + np.array([0.0, 9.0, 0.0])
        arm = top + np.array([r.r[i][0] * side, 0.12, r.r[i][1] * side]) * 2.2
        strut(M['metal'], foot, top, 0.16, (1.0, 1.0, 1.0))
        strut(M['metal'], top, arm, 0.10, (1.0, 1.0, 1.0))
        c = arm + np.array([r.r[i][0] * side, 0.0, r.r[i][1] * side]) * 0.3
        M['metal'].obox(float(c[0]), float(c[2]), float(r.r[i][0]), float(r.r[i][1]), 0.42, 0.14, float(c[1] - 0.06), float(c[1] + 0.05), (0.9, 0.9, 0.9), bottom=True)
    for r in (a1, a2, a3):
        e = edge[r.id]
        up = [i for i in range(r.n) if r.y[i] > ROAD_Y + 0.35]
        for i in range(up[0] + 4, up[-1], 9):
            lamp(r, i, e[i] + 0.5 + 0.33, -1.0)
            if r is a2:
                lamp(r, i, LEFT - 0.33, 1.0)

    # ---- a guide board over the start of the climb and one at the first tower
    def gantry(r, i, key, width=7.0):
        o0, o1 = LEFT - 1.3, edge[r.id][i] + 0.5 + 1.3
        ground = BASE if r.y[i] < ROAD_Y + 0.4 else float(r.y[i])
        for off in (o0, o1):
            q = r.xz[i] + r.r[i] * off
            strut(M['metal'], (q[0], ground, q[1]), (q[0], r.y[i] + 7.4, q[1]), 0.32, (1.0, 1.0, 1.0))
        strut(M['metal'], P(r, i, o0, 7.2), P(r, i, o1, 7.2), 0.30, (1.0, 1.0, 1.0))
        strut(M['metal'], P(r, i, o0, 6.2), P(r, i, o1, 6.2), 0.22, (1.0, 1.0, 1.0))
        centre = np.array(P(r, i, (o0 + o1) / 2, 6.7)) - np.array([r.t[i][0], 0.0, r.t[i][1]]) * 0.25
        guide.board(kit, key, tuple(centre), (float(r.r[i][0]), float(r.r[i][1])), width, width / 3)
    gantry(a1, 22, 'bridge', 6.0)
    gantry(a3, a3.n - 30, 'seomyeon_ahead', 6.0)

    # ---- views (the driver in the second lane), reflections
    views = []

    def look(name, r, i, turn=0.0, ahead=10, off=None, up=1.2):
        off = r.lane_off if off is None else off
        j = min(r.n - 1, i + ahead)
        px, py, pz = P(r, i, off, up)
        tx, ty, tz = P(r, j, off, up - 0.25)
        if turn:
            c, k = math.cos(math.radians(turn)), math.sin(math.radians(turn))
            dx, dz = tx - px, tz - pz
            tx, tz = px + dx * c + dz * k, pz + dz * c - dx * k    # turn > 0: to the right
        views.append({'name': name, 'px': px, 'py': py, 'pz': pz, 'tx': tx, 'ty': ty, 'tz': tz, 'fov': 62})
    for r in (a1, a2, a3):
        r.lane_off = r.median / 2 + 1.5 * r.lw
    look('A1_040_driver', a1, 10)
    look('A1_200_driver', a1, 50)
    look('A1_400_driver', a1, 100)
    look('A1_560_driver', a1, 140)
    look('A2_020_driver', a2, 5)
    look('A2_100_tower_ahead', a2, 25)
    look('A2_300_midspan', a2, 75)
    look('A2_300_glance_right', a2, 75, 50.0)
    look('A2_300_glance_left', a2, 75, -50.0)
    look('A2_460_tower_ahead', a2, 115)
    look('A3_100_driver', a3, 25)
    look('A3_400_driver', a3, 100)
    look('A3_640_landing', a3, 160)
