"""Haeundae as the drive begins: a boulevard between glass towers (Marine City) that opens onto the sea and the bridge.

What says "Haeundae" from the driver's seat: very tall, curved glass towers on both sides, three of them far taller than the
rest; shops in their podiums at street level; a wide, clean street with a planted median; and at its end the sea, the bridge
and a choice: straight on up the ramp, or right along the sea wall with its concrete tetrapods toward Gwangalli. Only that
structure is kept. No tower is a copy of a real one and none carries a name; signs are generic trade words.

Roads, kerbs, sidewalks, flat ground and the driving surfaces are districts/ring.py's (segments H0, H1, F, B1)."""
import json
import math

import numpy as np
from shapely import affinity
from shapely.geometry import LineString, Polygon
from shapely.ops import unary_union

from busan_kit import frontage, guide, street, towers
from busan_kit.geo import DATA
from busan_kit.kit import Kit
from busan_kit.materials import MAT
from busan_kit.mesh import flat
from districts.ring import Road, ease, ribbon, wall

NET = DATA / 'LandmarkNetwork.json'
NOTE = 'Generated by tools/districts/haeundae.py from tools/network.py.'
SEED = 1113
ROAD_Y, KERB = 4.0, 0.16
BASE = ROAD_Y + KERB
PODIUM = 4                                    # storeys of shops under a tower
GLASS = [(0.78, 0.92, 1.02), (0.86, 0.98, 1.0), (0.92, 0.94, 0.98), (0.80, 0.96, 0.94), (1.0, 0.96, 0.88), (0.74, 0.84, 0.96)]
CONCRETE, RAIL = (0.74, 0.74, 0.72), (0.70, 0.72, 0.74)


def unit(v):
    v = np.asarray(v, dtype=float)
    return v / np.linalg.norm(v)


def build(tex_dir=None):
    if tex_dir is not None:
        guide.make_guide(tex_dir)
        towers.make_tower_textures(tex_dir)
    net = json.loads(NET.read_text(encoding='utf-8'))
    O, EA, EB = np.array(net['frame']['origin']), np.array(net['frame']['a']), np.array(net['frame']['b'])

    def W(a, b):
        p = O + EA * a + EB * b
        return (float(p[0]), float(p[1]))
    heading = math.atan2(EA[1], EA[0])
    kit = Kit(dict(MAT, **guide.MATERIAL, **towers.MATERIAL), SEED, ROAD_Y, KERB, 11.25)
    M, rng = kit.M, kit.rng
    roads = {s['id']: Road(s) for s in net['segments']}
    h0, h1, f, b1 = roads['H0'], roads['H1'], roads['F'], roads['B1']
    boulevard = LineString(np.vstack([h1.xz, f.xz[1:]]))     # the boulevard is H1 and the fork F in one line
    L = boulevard.length
    kh = kit.along(boulevard, 11.25)
    kb = kit.along(LineString(b1.xz), 6.5)
    k0 = kit.along(LineString(h0.xz), 6.5)
    every_road = unary_union([LineString(r.xz).buffer(r.right + 6.0) for r in roads.values()])
    hill = Polygon([W(-104, -1000), (W(524, -1000)), W(524, -300), W(-104, -300)]).buffer(12.0)
    taken = []                                               # footprints so far: nothing is built into something else

    def plot(k, s0, s1, d0, d1):
        return Polygon([k.pose(s0, d0)[:2], k.pose(s1, d0)[:2], k.pose(s1, d1)[:2], k.pose(s0, d1)[:2]]).buffer(0)

    def free(p, roads_too=True):
        return not any(p.intersects(q) for q in taken) and not p.intersects(hill) and not (roads_too and p.buffer(-0.5).intersects(every_road))

    def tower_plot(k, s0, s1, side, line_off, height, lobes=0, bulge=0.0, depth=40.0, tint=None):
        """A podium of shops on the building line and a glass tower standing on it."""
        d0, d1 = side * line_off, side * (line_off + depth)
        base = plot(k, s0, s1, d0, d1)
        if not free(base, False):
            return
        taken.append(base)
        frontage.building(k, base, PODIUM, True)
        cx, cz, ux, uz = k.pose((s0 + s1) / 2, (d0 + d1) / 2)
        shape = towers.rounded(cx, cz, (s1 - s0) / 2 - 5.0, depth / 2 - 5.5, math.atan2(uz, ux), lobes, bulge)
        towers.glass_tower(kit, shape, BASE + 4.2 + (PODIUM - 1) * frontage.FLOOR + 0.9, BASE + height, tint or rng.choice(GLASS))

    def block_plot(k, s0, s1, side, line_off, storeys, depth=30.0):
        base = plot(k, s0, s1, side * line_off, side * (line_off + depth))
        if free(base, False):
            taken.append(base)
            frontage.building(k, base, storeys, True)

    # ---- the boulevard: towers and their podiums behind a wide paved forecourt
    RIGHT, LEFT = 20.5, 17.5                                 # building lines, metres from the road's centre line
    for s0, s1, height, lobes, bulge in ((14, 76, 150, 0, 0.0), (166, 236, 190, 4, 0.06), (250, 314, 300, 3, 0.16), (326, 388, 278, 3, 0.16), (400, 458, 252, 3, 0.16)):
        tower_plot(kh, s0, s1, 1.0, RIGHT, height, lobes, bulge, tint=(0.80, 0.94, 1.02) if height > 240 else None)
    block_plot(kh, 90, 152, 1.0, RIGHT, 12)
    for s0, s1, height, lobes, bulge in ((96, 166, 172, 0, 0.0), (256, 326, 205, 4, 0.05), (416, 470, 142, 0, 0.0)):
        tower_plot(kh, s0, s1, -1.0, LEFT, height, lobes, bulge)
    block_plot(kh, 20, 82, -1.0, LEFT, 15)
    block_plot(kh, 180, 242, -1.0, LEFT, 8)
    block_plot(kh, 340, 402, -1.0, LEFT, 10)
    pts_r = [kh.pose(s, 11.25 + 4.9 + (3.25 * ease((s - (L - 110.0)) / 70.0)))[:2] for s in np.arange(0.0, L - 46.0, 4.0)]
    fore = Polygon(pts_r + [kh.pose(s, RIGHT)[:2] for s in np.arange(0.0, L - 46.0, 4.0)][::-1]).buffer(0)
    pts_l = [kh.pose(s, -(11.25 + 4.9))[:2] for s in np.arange(0.0, L - 46.0, 4.0)]
    fore = fore.union(Polygon(pts_l + [kh.pose(s, -LEFT)[:2] for s in np.arange(0.0, L - 46.0, 4.0)][::-1]).buffer(0))
    M['granite'].polygon(fore, flat(BASE + 0.004))
    lawn = Polygon([kh.pose(s, 1.05)[:2] for s in np.arange(6.0, L - 60.0, 4.0)] + [kh.pose(s, -1.05)[:2] for s in np.arange(6.0, L - 60.0, 4.0)][::-1]).buffer(0)
    M['grass'].polygon(lawn, flat(BASE + 0.03))
    for k, s in enumerate(np.arange(18.0, L - 50.0, 40.0)):
        widen = 3.25 * ease((s - (L - 110.0)) / 70.0)
        street.lamp(kh, s, 11.25 + widen + 0.9, -1.0)
        street.lamp(kh, s + 20.0, -(11.25 + 0.9), 1.0)

    # ---- the fork: which lanes go where, twice over the road and once on it; a crossing and signals at the junction
    def gantry(k, s, o0, o1, boards):
        x0, z0, ux, uz = k.pose(s, o0)
        x1, z1, _, _ = k.pose(s, o1)
        for x, z in ((x0, z0), (x1, z1)):
            M['metal'].frustum(x, z, 0.17, 0.15, BASE, BASE + 7.7, 10)
        cx, cz = (x0 + x1) / 2, (z0 + z1) / 2
        rx, rz = uz, -ux
        for y, hw in ((BASE + 7.45, 0.15), (BASE + 6.25, 0.11)):
            M['metal'].obox(cx, cz, rx, rz, abs(o1 - o0) / 2, hw, y - hw, y + hw, (1.0, 1.0, 1.0), bottom=True)
        for key, off, width in boards:
            bx, bz, _, _ = k.pose(s, off)
            guide.board(kit, key, (bx - ux * 0.3, BASE + 6.85, bz - uz * 0.3), (rx, rz), width, width / 3)
    gantry(kh, L - 255.0, 0.6, 12.3, (('bridge_ahead', 4.2, 5.4), ('gwangalli_right', 9.9, 4.6)))
    gantry(kh, L - 92.0, 0.6, 15.5, (('bridge_left_lanes', 4.75, 5.6), ('gwangalli_right_lanes', 11.25, 5.6)))
    turn_right = Polygon([(-2.5, 0.15), (0.75, 0.15), (0.75, -0.75), (1.15, -0.75), (0.6, -1.75), (0.05, -0.75), (0.45, -0.75), (0.45, -0.15), (-2.5, -0.15)])
    for s in (L - 118.0, L - 64.0):
        for off in (3.125, 6.375):
            street.arrow(kh, s, off)
        for off in (9.625, 12.875):
            if off > 11.0 and s < L - 100.0:
                continue                                     # (the fourth lane has not opened yet)
            x, z, ux, uz = kh.pose(s, off)
            M['paint_white'].polygon(affinity.translate(affinity.rotate(turn_right, math.atan2(uz, ux), origin=(0, 0), use_radians=True), x, z), flat(ROAD_Y + 0.008))
    street.zebra(kh, L - 58.0)
    names = ('Hyundai_Tucson_White', 'Hyundai_Azera_Silver', 'Hyundai_i30_Blue', 'Hyundai_Tucson_Graphite', 'Hyundai_Azera_Navy', 'Hyundai_i30_Black', 'Hyundai_Tucson_Black', 'Hyundai_i30_Burgundy', 'Hyundai_Porter_II_Blue', 'Generic_DeliveryTruck')
    cars = []                                                # waiting at the crossing in the oncoming lanes (cars have no collision)
    for lane in (-6.375, -9.625):                            # (the lane by the median is the moving cars')
        d = L - 58.0 + 9.6 + rng.uniform(0.0, 1.5)
        for _ in range(rng.choice([2, 3])):
            cars.append(street.car(kh, d, lane, True, rng.choice(names[:8])))
            d += rng.uniform(6.4, 8.5)
    for s in (60.0, 190.0, 198.5, 330.0):
        cars.append(street.car(kh, s, -10.1, True, rng.choice(names)))
    street.signal(kh, L - 50.0, 1.0)
    street.walk_signal(kh, L - 55.7, 1.0)
    street.walk_signal(kh, L - 55.7, -1.0)

    # ---- the sea-wall road toward Gwangalli: on the sea side a paved walk, a low wall with a rail and tetrapods in the water
    i0 = next(i for i in range(b1.n) if b1.s[i] > 96.0)      # past the corner
    edge = 13.1                                              # the shore runs this far left of the road's centre line
    ribbon(M['granite'], b1, -edge + 0.3, -(6.5 + 4.9), KERB + 0.004, i0, b1.n)
    wall(M['stone'], b1, -edge + 0.3, KERB, 1.25, 1.0, i0, b1.n, CONCRETE)
    wall(M['stone'], b1, -edge - 0.1, -4.5, 1.25, -1.0, i0, b1.n, CONCRETE)
    ribbon(M['stone'], b1, -edge - 0.1, -edge + 0.3, 1.25, i0, b1.n, CONCRETE)
    for h in (1.42, 1.62):
        for o0, o1 in ((-edge + 0.07, -edge + 0.13),):
            ribbon(M['painted'], b1, o0, o1, h, i0, b1.n, RAIL)
            ribbon(M['painted'], b1, o0, o1, h - 0.05, i0, b1.n, RAIL, up=False)
            wall(M['painted'], b1, o0, h - 0.05, h, -1.0, i0, b1.n, RAIL)
            wall(M['painted'], b1, o1, h - 0.05, h, 1.0, i0, b1.n, RAIL)
    for i in range(i0, b1.n, 1):
        x, _, z = b1.P(i, -edge + 0.1)
        M['painted'].frustum(x, z, 0.03, 0.03, ROAD_Y + 1.25, ROAD_Y + 1.64, 6, RAIL, cap=False)

    def strut(mesh, p0, p1, w, col):
        p0, p1 = np.array(p0, dtype=float), np.array(p1, dtype=float)
        d = unit(p1 - p0)
        u = unit(np.cross(d, (0.0, 1.0, 0.0) if abs(d[1]) < 0.9 else (1.0, 0.0, 0.0)))
        v = np.cross(d, u)
        c = [(u + v) * w / 2, (u - v) * w / 2, (-u - v) * w / 2, (-u + v) * w / 2]
        for k in range(4):
            a_, b_ = c[k], c[(k + 1) % 4]
            mesh.quad(tuple(p0 + a_), tuple(p0 + b_), tuple(p1 + b_ * 0.6), tuple(p1 + a_ * 0.6), tuple(a_ + b_), col=col)
        mesh.quad(tuple(p1 + c[0] * 0.6), tuple(p1 + c[1] * 0.6), tuple(p1 + c[2] * 0.6), tuple(p1 + c[3] * 0.6), tuple(d), col=col)
    legs = [np.array(v) for v in ((0.0, 1.0, 0.0), (0.943, -0.333, 0.0), (-0.471, -0.333, 0.816), (-0.471, -0.333, -0.816))]
    for i in range(i0, b1.n - 1):                            # tetrapods heaped against the wall, three rows deep
        for row, (off, y) in enumerate(((-edge - 1.6, 2.3), (-edge - 3.6, 1.2), (-edge - 5.8, 0.3))):
            for _ in range(2):
                q = b1.xz[i] + b1.r[i] * (off + rng.uniform(-0.7, 0.7)) + b1.t[i] * rng.uniform(0.0, 4.0)
                c = np.array([q[0], y + rng.uniform(-0.4, 0.4), q[1]])
                a, tilt = rng.uniform(0, 2 * math.pi), rng.uniform(-0.5, 0.5)
                rot = np.array([[math.cos(a), 0, math.sin(a)], [0, 1, 0], [-math.sin(a), 0, math.cos(a)]]) @ np.array([[1, 0, 0], [0, math.cos(tilt), -math.sin(tilt)], [0, math.sin(tilt), math.cos(tilt)]])
                shade = rng.uniform(0.62, 0.78)
                for leg in legs:
                    strut(M['stone'], c, c + rot @ leg * 1.5, 0.95, (shade, shade, shade * 0.98))
    for s0, s1, kind, value in ((104, 160, 'block', 12), (172, 236, 'tower', 164)):      # the town side of the sea-wall road
        if kind == 'tower':
            tower_plot(kb, s0, s1, 1.0, 12.0, value, 0, 0.0, depth=36.0)
        else:
            block_plot(kb, s0, s1, 1.0, 12.0, value)
    for k, s in enumerate(np.arange(110.0, kb.LEN - 30.0, 36.0)):
        street.lamp(kb, s, -(6.5 + 0.9), 1.0)

    # ---- the way in from the tunnel: apartment blocks either side
    for side, line_off in ((1.0, 12.5), (-1.0, 12.5)):
        for s0 in np.arange(40.0, k0.LEN - 30.0, 62.0):
            block_plot(k0, s0, s0 + 50.0, side, line_off, rng.choice([18, 22, 25, 15]), depth=24.0)
    for s in np.arange(30.0, k0.LEN - 96.0, 40.0):
        street.lamp(k0, s, 6.5 + 0.9, -1.0)

    # ---- behind and beyond: more towers and plain blocks, thinning out with distance; a mountain far behind them
    def scatter(a0, a1, b0, b1_, count, tall):
        for _ in range(count):
            a, b = rng.uniform(a0, a1), rng.uniform(b0, b1_)
            x, z = W(a, b)
            if tall:
                shape = towers.rounded(x, z, rng.uniform(14, 22), rng.uniform(11, 16), rng.uniform(0, math.pi), rng.choice([0, 0, 3, 4]), 0.08)
            else:
                w, d, t = rng.uniform(16, 34), rng.uniform(12, 22), rng.uniform(0, math.pi)
                shape = Polygon([(x + math.cos(t) * i * w / 2 - math.sin(t) * j * d / 2, z + math.sin(t) * i * w / 2 + math.cos(t) * j * d / 2) for i, j in ((-1, -1), (1, -1), (1, 1), (-1, 1))])
            if not free(shape.buffer(6.0)):
                continue
            taken.append(shape)
            if tall:
                towers.glass_tower(kit, shape, BASE - 0.1, BASE + rng.uniform(95, 215), rng.choice(GLASS))
            else:
                frontage.block(kit, shape, rng.choice([8, 12, 15, 18, 22, 25]), BASE - 0.1)
    # a cluster of residential towers by the water east of the fork, 140-270 m (what the bridge and the fork look at on the
    # Haeundae side; the land there was a few scattered blocks). Not a copy of any real tower.
    for _ in range(110):
        a, b = rng.uniform(870, 1600), rng.uniform(-340, 165)
        if b > 35 and a < 960:                               # (the fork's own waterfront stays open toward the bridge)
            continue
        x, z = W(a, b)
        shape = towers.rounded(x, z, rng.uniform(15, 22), rng.uniform(12, 17), rng.uniform(0, math.pi), rng.choice([0, 3, 4]), 0.08)
        if not free(shape.buffer(9.0)):
            continue
        taken.append(shape)
        towers.glass_tower(kit, shape, BASE - 0.1, BASE + rng.uniform(140, 270), rng.choice(GLASS))
    scatter(600, 760, -640, -40, 7, True)                    # between the boulevard and the hill
    scatter(590, 770, -660, 30, 30, False)
    scatter(850, 1400, -900, 160, 16, True)                  # east of the boulevard, out to the horizon
    scatter(840, 1500, -1000, 170, 90, False)
    scatter(560, 1300, -1300, -760, 40, False)               # north of the way in
    cx, cz, top, reach, n, rings = 1750.0, -1500.0, 480.0, 1150.0, 28, 9
    pts = []
    for j in range(rings + 1):
        for i in range(n):
            t = 2 * math.pi * i / n
            r = reach * j / rings * (1.0 + 0.16 * math.sin(3 * t + 0.7) + 0.08 * math.sin(5 * t))
            x, z = W(cx + r * math.cos(t), cz + r * math.sin(t) * 0.8)
            h = top * (1.0 - ease(j / rings)) * (1.0 + 0.1 * math.sin(2 * t))
            pts.append((x, BASE - 2.0 + h, z))
    first = M['hill']._add(pts, [], (1, 1, 1))
    a_, b_, c_ = np.array(pts[0]), np.array(pts[n]), np.array(pts[n + 1])
    upward = float(np.cross(b_ - a_, c_ - a_)[1]) > 0
    for j in range(rings):
        for i in range(n):
            q0, q1, q2, q3 = first + j * n + i, first + (j + 1) * n + i, first + (j + 1) * n + (i + 1) % n, first + j * n + (i + 1) % n
            M['hill'].t += [q0, q1, q2, q0, q2, q3] if upward else [q0, q2, q1, q0, q3, q2]

    # ---- views (the driver bound for Gwangalli keeps right; for the bridge, left), reflections
    vs = [street_view(kh, 'D%03d_driver' % d, d, 9.625) for d in (30, 130, 230, 330, 420)]
    vs.append(street_view(kh, 'F_bridge_lanes', L - 100.0, 6.375))
    vs.append(street_view(kh, 'L230_glance_left', 230, 9.625, -50.0))
    vs.append(street_view(kh, 'R230_glance_right', 230, 9.625, 50.0))
    vs.append(street_view(kh, 'U300_towers', 300, 9.625, 25.0, lift=26.0))
    vs.append(street_view(kh, 'K150_kerb_close', 150, 9.625, 24.0, dist=12.0))
    vs.append(street_view(kb, 'B1_120_driver', 120, 1.625))
    vs.append(street_view(kb, 'B1_180_glance_left', 180, 1.625, -55.0))
    vs.append(street_view(k0, 'H0_150_driver', 150, 4.875))
    probes = [{'name': 'Boulevard', 'pos': [kh.pose(L / 2, 6.0)[0], ROAD_Y + 2.0, kh.pose(L / 2, 6.0)[1]], 'importance': 1},
              {'name': 'Seawall', 'pos': [kb.pose(170.0, 0.0)[0], ROAD_Y + 2.0, kb.pose(170.0, 0.0)[1]], 'importance': 1,
               'box': [kb.pose(170.0, 0.0)[0], 60.0, kb.pose(170.0, 0.0)[1], 260.0, 140.0, 260.0]}]
    scene = {'note': NOTE, 'heading': heading, 'sunYaw': 0.0, 'sunPitch': 38.0, 'probe': probes[0]['pos'], 'probes': probes, 'cars': cars, 'views': vs}
    return kit, scene


def street_view(k, name, s, off, turn=0.0, dist=40.0, lift=0.0):
    x, z, ux, uz = k.pose(s, off)
    c, n = math.cos(math.radians(turn)), math.sin(math.radians(turn))
    rx, rz = ux * c + uz * n, uz * c - ux * n                # turn > 0: to the right
    return {'name': name, 'px': x, 'py': ROAD_Y + 1.2, 'pz': z, 'tx': x + rx * dist, 'ty': ROAD_Y + 0.95 + lift, 'tz': z + rz * dist, 'fov': 62}
