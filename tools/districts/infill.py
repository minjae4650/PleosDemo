"""What stood empty beside the drive: open ground the driver looks across (the fork at Haeundae, the way into the junction J, the
junction T, the ends of the tunnel) built up with rows of buildings, the way the land beside a Busan road is.

It builds last: it reads where the other districts stand (footprints.json that tools/build_district.py leaves beside each
district's output) and the open ground that districts/ring.py leaves, and builds only on that ground, within sight of a road the
routes drive. Along each route, on both sides, a first row of shop buildings faces the road from the edge of the sidewalk; behind
it a second, taller row; then plain blocks. No building is a copy of a real one."""
import json
import math

import numpy as np
from shapely.geometry import LineString, Polygon, shape
from shapely.ops import unary_union
from shapely.prepared import prep

from busan_kit import frontage, guide, towers
from busan_kit.geo import DATA
from busan_kit.kit import Kit
from busan_kit.materials import MAT

NET = DATA / 'LandmarkNetwork.json'
OUT = r'C:\c\busan-out'
NOTE = 'Generated by tools/districts/infill.py from tools/network.py and the other districts.'
SEED = 1115
ROAD_Y, KERB = 4.0, 0.16
BASE = ROAD_Y + KERB
SIGHT = 120.0                 # how far from a driven line the ground is built on
GLASS = [(0.80, 0.90, 0.98), (0.92, 0.94, 0.96), (0.78, 0.92, 0.90), (0.72, 0.80, 0.92)]


def footprints():
    placed, land = [], None
    for name in ('ring', 'gwangalli', 'bridge', 'haeundae', 'seomyeon'):
        try:
            data = json.loads(open('%s\\%s\\footprints.json' % (OUT, name), encoding='utf-8').read())
        except FileNotFoundError:
            continue
        placed += [shape(p) for p in data['placed']]
        if data.get('land'):
            land = shape(data['land'])
    return placed, land


def routes(net):
    """Each route's street-level runs as (line, tangent array) pieces."""
    out = []
    for route in net['routes']:
        run = []
        for p in route['path'] + route['path'][:1]:
            if p[1] > ROAD_Y + 1e-3:
                if len(run) > 1:
                    out.append(LineString(run))
                run = []
            else:
                run.append((p[0], p[2]))
        if len(run) > 1:
            out.append(LineString(run))
    return out


def build(tex_dir=None):
    if tex_dir is not None:
        guide.make_guide(tex_dir)
        towers.make_tower_textures(tex_dir)
    net = json.loads(NET.read_text(encoding='utf-8'))
    EA = np.array(net['frame']['a'])
    heading = math.atan2(EA[1], EA[0])
    kit = Kit(dict(MAT, **guide.MATERIAL, **towers.MATERIAL), SEED, ROAD_Y, KERB, 6.5)
    rng = kit.rng
    placed, land = footprints()
    lines = routes(net)
    if land is None:
        raise SystemExit('build the ring district first (its open ground is in C:\\c\\busan-out\\ring\\footprints.json)')
    sight = unary_union([ln.buffer(SIGHT) for ln in lines])
    taken = unary_union([p.buffer(3.0) for p in placed])
    ground = land.intersection(sight).difference(taken).buffer(-0.5)
    mine = []
    inside = prep(ground)

    def fits(p):
        if p.is_empty or not p.is_valid:
            return False
        if p.difference(ground).area > 0.04 * p.area:
            return False
        return not any(p.buffer(1.5).intersects(q) for q in mine)

    def plot(line, s, off0, off1, w, side):
        k = kit.along(line)
        pts = [k.pose(s, side * off0)[:2], k.pose(s + w, side * off0)[:2], k.pose(s + w, side * off1)[:2], k.pose(s, side * off1)[:2]]
        return Polygon(pts).buffer(0)

    rows = 0
    for line in lines:
        k = kit.along(line)
        for side in (1.0, -1.0):
            s = 0.0
            while s < line.length - 12.0:
                # where the open ground begins, measured out from the driven line
                front = None
                for d in np.arange(4.0, 70.0, 1.0):
                    x, z, _, _ = k.pose(s + 6.0, side * d)
                    if inside.contains(Polygon([(x - 1, z - 1), (x + 1, z - 1), (x + 1, z + 1), (x - 1, z + 1)])):
                        front = d
                        break
                if front is None:
                    s += 6.0
                    continue
                w = rng.uniform(14.0, 28.0)
                depth = rng.uniform(18.0, 24.0)
                p = plot(line, s, front + 0.5, front + 0.5 + depth, w, side)
                if not fits(p):
                    s += 4.0
                    continue
                mine.append(p)
                frontage.building(k, p, rng.choice([3, 4, 5, 5, 6, 7, 8, 10]), front < 24.0)
                rows += 1
                # behind it a taller one, and beyond that a block, as far as the ground goes
                back = front + 0.5 + depth + rng.uniform(6.0, 10.0)
                for n in range(2):
                    d2 = rng.uniform(20.0, 30.0)
                    q = plot(line, s + rng.uniform(-3.0, 3.0), back, back + d2, w * rng.uniform(0.8, 1.1), side)
                    if fits(q):
                        mine.append(q)
                        if n == 0 and rng.random() < 0.25 and q.area > 380:
                            c = q.centroid
                            t = math.atan2(k.pose(s, 0)[3], k.pose(s, 0)[2])
                            towers.glass_tower(kit, towers.rounded(c.x, c.y, w * 0.42, d2 * 0.42, t, 4, 0.04), BASE - 0.1, BASE + rng.uniform(60, 120), rng.choice(GLASS), crown=0.06)
                        else:
                            frontage.block(k, q, rng.choice([8, 10, 12, 15, 18] if n == 0 else [12, 15, 20, 25]), BASE - 0.1)
                    back += d2 + rng.uniform(6.0, 10.0)
                s += w + rng.uniform(1.0, 3.0)
    print('infill: %d buildings in %d rows (open ground in sight %.0f m2)' % (len(mine), rows, ground.area))
    c = lines[0].interpolate(0.5, normalized=True)
    probes = [{'name': 'Infill', 'pos': [c.x, ROAD_Y + 2.0, c.y], 'importance': 0}]
    scene = {'note': NOTE, 'heading': heading, 'sunYaw': 0.0, 'sunPitch': 38.0, 'probe': probes[0]['pos'], 'probes': [], 'cars': [], 'views': []}
    return kit, scene
